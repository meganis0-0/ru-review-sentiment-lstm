"""Страница запуска интерфейса.

Предсказание тональности подключается после обучения модели.
"""

import streamlit as st

st.set_page_config(page_title="Тональность отзывов")
st.title("Тональность отзывов на русском")
st.write("Классификатор на LSTM: negative, neutral или positive.")
st.info("Модель ещё не подключена. Страница проверяет, что сервис интерфейса поднимается.")

review = st.text_area("Текст отзыва")
if st.button("Оценить") and review.strip():
    st.warning("Предсказание появится, когда будет готов чекпоинт модели.")
